"""The user's command folder (~/.local/bin): the ``claude-kimi`` command, PATH, Claude Code install.

Everything here is per user and asked for first (setup prompts, or explicit flags when
non-interactive):

* ``claude-kimi`` (``claude-kimi.cmd`` on Windows) is a tiny generated wrapper that runs this
  repo's launcher from any folder. Its first lines carry a marker; a file without it is never
  overwritten or deleted.
* On Windows the folder is added to the *user* PATH by editing HKCU\\Environment directly (keeping
  the existing entries and value type; ``setx`` can silently truncate PATH) and broadcasting the
  change. macOS/Linux PATH lives in shell startup files, which are only ever printed as a hint.
* Claude Code is installed only with the official installer from claude.ai.

Test hooks: KGW_COMMAND_DIR overrides the folder; KGW_NO_CLAUDE_INSTALL=1 makes the installer refuse.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import common

MARKER = "kimi-bedrock-gateway launcher"
_ENV_KEY = "Environment"
_MACHINE_ENV_KEY = r"SYSTEM\CurrentControlSet\Control\Session Manager\Environment"


def _is_windows() -> bool:
    return os.name == "nt"


def command_dir() -> Path:
    return Path(os.environ.get("KGW_COMMAND_DIR") or Path.home() / ".local" / "bin")


def command_path() -> Path:
    return command_dir() / ("claude-kimi.cmd" if _is_windows() else "claude-kimi")


def wrapper_content() -> str:
    env = {"KGW_HOME": str(common.state_dir())} if os.environ.get("KGW_HOME") else {}
    if _is_windows():
        # Calls the venv's Python directly: no PowerShell execution policy or quoting involved.
        python = common.venv_python()
        manage = common.REPO_ROOT / "scripts" / "manage.py"
        sets = "".join(f'set "{k}={v}"\r\n' for k, v in env.items())
        return ("@echo off\r\n"
                f"rem {MARKER} (generated by setup; safe to delete)\r\n"
                "setlocal\r\n" + sets
                + f'"{python}" "{manage}" launch-claude -- %*\r\n'
                "exit /b %ERRORLEVEL%\r\n")
    exports = "".join(f"export {k}='{v}'\n" for k, v in env.items())
    return ("#!/bin/sh\n"
            f"# {MARKER} (generated by setup; safe to delete)\n"
            + exports
            + f'exec "{common.REPO_ROOT / "claude-kimi.sh"}" "$@"\n')


# ------------------------------------------------------------------- PATH


def _norm(entry: str) -> str:
    expanded = os.path.expandvars(os.path.expanduser(entry.strip().strip('"')))
    return os.path.normcase(os.path.normpath(expanded)).rstrip("\\/") if expanded else ""


def _in(entries: list[str], directory: Path) -> bool:
    target = _norm(str(directory))
    return any(_norm(e) == target for e in entries if e.strip())


def _win_read(root_name: str, key: str) -> tuple[str, int | None]:
    import winreg  # noqa: PLC0415

    root = getattr(winreg, root_name)
    try:
        with winreg.OpenKey(root, key, 0, winreg.KEY_READ) as k:
            value, kind = winreg.QueryValueEx(k, "Path")  # winreg never expands REG_EXPAND_SZ
            return str(value or ""), kind
    except OSError:
        return "", None


def path_status(directory: Path | None = None) -> dict[str, bool]:
    """``now``: on this process's PATH. ``persistent``: new terminals will have it."""
    directory = directory or command_dir()
    now = _in(os.environ.get("PATH", "").split(os.pathsep), directory)
    if not _is_windows():
        return {"now": now, "persistent": now}
    user, _ = _win_read("HKEY_CURRENT_USER", _ENV_KEY)
    machine, _ = _win_read("HKEY_LOCAL_MACHINE", _MACHINE_ENV_KEY)
    return {"now": now, "persistent": _in(user.split(";") + machine.split(";"), directory)}


def _broadcast_environment_change() -> None:
    try:
        import ctypes  # noqa: PLC0415

        result = ctypes.c_ulong()
        # HWND_BROADCAST, WM_SETTINGCHANGE, SMTO_ABORTIFHUNG, 5 s: new terminals pick up the PATH.
        ctypes.windll.user32.SendMessageTimeoutW(0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000,
                                                 ctypes.byref(result))
    except Exception:  # noqa: BLE001 - best effort; a sign-out/in also applies it
        pass


def add_to_user_path(directory: Path | None = None) -> bool:
    """Windows only: append ``directory`` to the user PATH. Returns False if already present."""
    if not _is_windows():
        raise common.GatewayError("Only Windows PATH can be changed automatically.", code="unsupported")
    import winreg  # noqa: PLC0415

    directory = directory or command_dir()
    value, kind = _win_read("HKEY_CURRENT_USER", _ENV_KEY)
    entries = [e for e in value.split(";") if e.strip()]
    if _in(entries, directory):
        return False
    kind = kind if kind in (winreg.REG_SZ, winreg.REG_EXPAND_SZ) else winreg.REG_EXPAND_SZ
    with winreg.CreateKeyEx(winreg.HKEY_CURRENT_USER, _ENV_KEY, 0, winreg.KEY_SET_VALUE) as k:
        winreg.SetValueEx(k, "Path", 0, kind, ";".join(entries + [str(directory)]))
    _broadcast_environment_change()
    if not path_status(directory)["now"]:
        os.environ["PATH"] = os.environ.get("PATH", "") + os.pathsep + str(directory)
    return True


def posix_path_hint(directory: Path | None = None) -> str:
    directory = directory or command_dir()
    shell = os.path.basename(os.environ.get("SHELL", "zsh"))
    rc = "~/.bashrc" if shell == "bash" else "~/.zshrc" if shell == "zsh" else "your shell's startup file"
    shown = str(directory).replace(str(Path.home()), "$HOME", 1)
    return f'Add this line to {rc}, then open a new terminal:  export PATH="{shown}:$PATH"'


# --------------------------------------------------------- claude-kimi command


def command_status() -> dict[str, object]:
    path = command_path()
    text = ""
    if path.exists():
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            text = ""
    ours = MARKER in text
    return {"path": str(path), "installed": ours, "foreign": path.exists() and not ours,
            "current": ours and text == wrapper_content(), "dir_on_path": path_status()}


def install_command() -> bool:
    """Write (or refresh) the wrapper. Returns True if the file changed."""
    st = command_status()
    if st["foreign"]:
        raise common.GatewayError(f"{st['path']} exists and wasn't created by this gateway; leaving it alone.",
                                  hint="Rename or remove it, then run: gateway command install",
                                  code="command_conflict")
    if st["current"]:
        return False
    path = command_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(wrapper_content().encode("utf-8"))
    if not _is_windows():
        os.chmod(tmp, 0o755)
    os.replace(tmp, path)
    return True


def remove_command() -> bool:
    if command_status()["installed"]:
        command_path().unlink()
        return True
    return False


# ------------------------------------------------------------- Claude Code


def claude_installer_command() -> list[str]:
    if _is_windows():
        return ["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-Command",
                "irm https://claude.ai/install.ps1 | iex"]
    return ["bash", "-c", "curl -fsSL https://claude.ai/install.sh | bash"]


def install_claude_code() -> int:
    """Run Anthropic's official Claude Code installer, showing its output. Returns its exit code."""
    if os.environ.get("KGW_NO_CLAUDE_INSTALL") == "1":
        raise common.GatewayError("Claude Code installation is disabled here (KGW_NO_CLAUDE_INSTALL=1).",
                                  code="install_disabled")
    try:
        return subprocess.call(claude_installer_command())
    except OSError as exc:
        raise common.GatewayError(f"Could not run the Claude Code installer: {exc}", code="install_failed") from None
