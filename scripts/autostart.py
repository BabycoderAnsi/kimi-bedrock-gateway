"""Start the gateway (and optionally Claude Code) when the user logs in.

Per-user mechanisms only, never system-wide and never with elevated rights:

* macOS:   LaunchAgents in ~/Library/LaunchAgents (gateway: ``start --background`` at load;
           Claude Code: ``open -a Terminal`` on a generated ``.command`` file).
* Linux:   XDG autostart entries in ~/.config/autostart (runs inside the desktop session, after
           the Secret Service keyring is unlocked).
* Windows: ``.cmd`` files in the user's Startup folder.

Every location can be overridden with an environment variable so tests never touch the real
login items: KGW_LAUNCH_AGENTS_DIR, KGW_XDG_AUTOSTART_DIR, KGW_STARTUP_DIR. KGW_AUTOSTART_NO_LOAD=1
skips launchctl. A non-default KGW_HOME gets its own label suffix, so instances never collide.
"""

from __future__ import annotations

import os
import plistlib
import subprocess
from dataclasses import dataclass
from pathlib import Path

import common

LABEL_BASE = "com.kimi-bedrock-gateway"
KINDS = ("gateway", "claude")


@dataclass(frozen=True)
class Entry:
    kind: str  # gateway | claude
    path: Path
    content: bytes
    mode: int = 0o600


def label(kind: str) -> str:
    suffix = common.instance_suffix()
    base = LABEL_BASE + (f".{suffix}" if suffix else "")
    return base if kind == "gateway" else f"{base}.claude"


def _system() -> str:
    return common.detect_platform().system  # Darwin | Linux | Windows


def _manage_args(*args: str) -> list[str]:
    return [str(common.venv_python()), str(common.REPO_ROOT / "scripts" / "manage.py"), "--non-interactive", *args]


def _instance_env() -> dict[str, str]:
    return {"KGW_HOME": str(common.state_dir())} if os.environ.get("KGW_HOME") else {}


def autostart_dir() -> Path:
    system = _system()
    if system == "Darwin":
        return Path(os.environ.get("KGW_LAUNCH_AGENTS_DIR") or Path.home() / "Library" / "LaunchAgents")
    if system == "Windows":
        appdata = os.environ.get("APPDATA") or str(Path.home() / "AppData" / "Roaming")
        return Path(os.environ.get("KGW_STARTUP_DIR")
                    or Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup")
    xdg = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Path(os.environ.get("KGW_XDG_AUTOSTART_DIR") or Path(xdg) / "autostart")


def entry_path(kind: str) -> Path:
    ext = {"Darwin": ".plist", "Windows": ".cmd"}.get(_system(), ".desktop")
    return autostart_dir() / f"{label(kind)}{ext}"


def claude_command_file() -> Path:
    """The script a terminal runs at login to launch Claude Code through the gateway (macOS)."""
    return common.state_dir() / "autostart" / "claude-kimi.command"


# --------------------------------------------------------------------- content


def _desktop_quote(arg: str) -> str:
    # Desktop Entry spec: quote, and escape ", `, $ and \ inside quotes.
    return '"' + "".join("\\" + c if c in '"`$\\' else c for c in arg) + '"'


def _sh_quote(arg: str) -> str:
    return "'" + arg.replace("'", "'\"'\"'") + "'"


def build_entries(open_claude: bool, claude_workdir: Path) -> list[Entry]:
    system = _system()
    p = common.paths()
    env = _instance_env()
    entries: list[Entry] = []
    if system == "Darwin":
        log = str(p.log_dir / "autostart.log")
        entries.append(Entry("gateway", entry_path("gateway"), plistlib.dumps({
            "Label": label("gateway"),
            "ProgramArguments": _manage_args("start", "--background"),
            "EnvironmentVariables": env,
            "RunAtLoad": True,
            # start --background detaches the proxy and exits; keep launchd from killing it.
            "AbandonProcessGroup": True,
            # The login keychain (credential store) is only available in the GUI session.
            "LimitLoadToSessionType": "Aqua",
            "ProcessType": "Background",
            "StandardOutPath": log,
            "StandardErrorPath": log,
        })))
        if open_claude:
            script = (
                "#!/bin/sh\n"
                "# Generated by kimi-bedrock-gateway autostart: Claude Code through the gateway at login.\n"
                + "".join(f"export {k}={_sh_quote(v)}\n" for k, v in env.items())
                + f"cd {_sh_quote(str(claude_workdir))} || cd \"$HOME\"\n"
                # A login shell, so PATH includes where Claude Code is installed (e.g. ~/.local/bin).
                + f'exec "${{SHELL:-/bin/zsh}}" -lc \'exec "$0" "$@"\' {_sh_quote(str(common.REPO_ROOT / "claude-kimi.sh"))} "$@"\n'
            )
            entries.append(Entry("claude", claude_command_file(), script.encode(), 0o700))
            entries.append(Entry("claude", entry_path("claude"), plistlib.dumps({
                "Label": label("claude"),
                "ProgramArguments": ["/usr/bin/open", "-a", "Terminal", str(claude_command_file())],
                "RunAtLoad": True,
                "LimitLoadToSessionType": "Aqua",
            })))
    elif system == "Windows":
        sets = "".join(f'set "{k}={v}"\r\n' for k, v in env.items())
        pythonw = common.venv_python().with_name("pythonw.exe")
        manage = common.REPO_ROOT / "scripts" / "manage.py"
        entries.append(Entry("gateway", entry_path("gateway"), (
            "@echo off\r\nrem Generated by kimi-bedrock-gateway autostart: start the gateway at logon.\r\n"
            f'{sets}start "" /b "{pythonw}" "{manage}" --non-interactive start --background\r\n').encode()))
        if open_claude:
            ps1 = common.REPO_ROOT / "claude-kimi.ps1"
            entries.append(Entry("claude", entry_path("claude"), (
                "@echo off\r\nrem Generated by kimi-bedrock-gateway autostart: Claude Code through the gateway.\r\n"
                f'{sets}start "Claude Code (Kimi K3)" /d "{claude_workdir}" powershell -NoExit -NoProfile '
                f'-ExecutionPolicy Bypass -File "{ps1}"\r\n').encode()))
    else:
        prefix = (["env"] + [f"{k}={v}" for k, v in env.items()]) if env else []
        exec_gateway = " ".join(_desktop_quote(a) for a in prefix + _manage_args("start", "--background"))
        entries.append(Entry("gateway", entry_path("gateway"), (
            "[Desktop Entry]\nType=Application\nName=Kimi Bedrock Gateway\n"
            "Comment=Start the local LiteLLM gateway for Kimi K3 (kimi-bedrock-gateway)\n"
            f"Exec={exec_gateway}\nTerminal=false\nNoDisplay=true\nX-GNOME-Autostart-enabled=true\n").encode()))
        if open_claude:
            inner = (" ".join(f"export {k}={_sh_quote(v)};" for k, v in env.items())
                     + f" cd {_sh_quote(str(claude_workdir))} || cd \"$HOME\"; "
                     + f"exec {_sh_quote(str(common.REPO_ROOT / 'claude-kimi.sh'))}")
            entries.append(Entry("claude", entry_path("claude"), (
                "[Desktop Entry]\nType=Application\nName=Claude Code (Kimi K3)\n"
                "Comment=Claude Code through the Kimi Bedrock Gateway\n"
                f"Exec=sh -c {_desktop_quote(inner)}\nTerminal=true\nX-GNOME-Autostart-enabled=true\n").encode()))
    return entries


# ------------------------------------------------------------------ operations


def _launchctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["launchctl", *args], capture_output=True, text=True, check=False)


def _load_allowed() -> bool:
    return _system() == "Darwin" and os.environ.get("KGW_AUTOSTART_NO_LOAD") != "1"


def _write(entry: Entry) -> None:
    entry.path.parent.mkdir(parents=True, exist_ok=True)
    tmp = entry.path.with_name(entry.path.name + ".tmp")
    tmp.write_bytes(entry.content)
    os.chmod(tmp, entry.mode)
    os.replace(tmp, entry.path)


def enable(open_claude: bool, claude_workdir: Path, load_gateway_now: bool) -> list[Path]:
    """Write (or rewrite) the login items. Returns the files written."""
    entries = build_entries(open_claude, claude_workdir)
    written: list[Path] = []
    if not open_claude:
        disable(kinds=("claude",))
    p = common.paths()
    common.ensure_private_dir(p.log_dir)
    for entry in entries:
        _write(entry)
        written.append(entry.path)
    if _system() == "Darwin":
        log = p.log_dir / "autostart.log"
        log.touch(exist_ok=True)
        common.restrict_permissions(log)
        if _load_allowed() and load_gateway_now:
            # Reload so an updated plist takes effect; RunAtLoad starts the gateway now.
            domain = f"gui/{os.getuid()}"
            _launchctl("bootout", f"{domain}/{label('gateway')}")
            res = _launchctl("bootstrap", domain, str(entry_path("gateway")))
            if res.returncode != 0:
                raise common.GatewayError(f"launchctl could not load the gateway login item: "
                                          f"{(res.stderr or res.stdout).strip()}", code="autostart_failed")
    return written


def disable(kinds: tuple[str, ...] = KINDS) -> list[Path]:
    removed: list[Path] = []
    for kind in kinds:
        if _load_allowed():
            _launchctl("bootout", f"gui/{os.getuid()}/{label(kind)}")
        targets = [entry_path(kind)] + ([claude_command_file()] if kind == "claude" else [])
        for path in targets:
            if path.exists():
                path.unlink()
                removed.append(path)
    return removed


def status() -> dict[str, dict[str, object]]:
    out: dict[str, dict[str, object]] = {}
    for kind in KINDS:
        path = entry_path(kind)
        info: dict[str, object] = {"installed": path.exists(), "path": str(path)}
        if _system() == "Darwin" and os.environ.get("KGW_AUTOSTART_NO_LOAD") != "1":
            info["loaded"] = _launchctl("print", f"gui/{os.getuid()}/{label(kind)}").returncode == 0
        out[kind] = info
    return out
